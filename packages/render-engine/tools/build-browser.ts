import { build } from 'esbuild';
import { readFileSync, readdirSync, mkdirSync, writeFileSync, statSync } from 'node:fs';
import { resolve, relative, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';
import ts from 'typescript';

const root = resolve(fileURLToPath(new URL('../../..', import.meta.url)));
const pkg = join(root, 'packages/render-engine');
const files: Record<string, string> = {};
function collect(dir: string): void {
  for (const name of readdirSync(join(root, dir)).sort()) {
    const path = `${dir}/${name}`;
    if (statSync(join(root, path)).isDirectory()) collect(path);
    else if (/\.(md|json|yaml|svg|txt)$/.test(name)) files[path] = readFileSync(join(root, path), 'utf8');
  }
}
for (const dir of ['evodesign/agentic_system/system_prompt', 'evodesign/agentic_system/common/assets',
  'evodesign/agentic_system/tool_services/public/icons/material-design-icons', 'evodesign/config/defaults']) collect(dir);
mkdirSync(join(pkg, 'src/generated'), { recursive: true });
writeFileSync(join(pkg, 'src/generated/browser_assets.ts'), `// Generated by tools/build-browser.ts. No .env or local credentials.\nexport const files: Record<string, string> = ${JSON.stringify(files)};\n`);
mkdirSync(join(pkg, 'dist'), { recursive: true });
// Emit a self-contained declaration so browser consumers never follow the
// runtime FS source into the default Node platform during type checking.
const fsTypes = ts.transpileDeclaration(readFileSync(join(pkg, 'src/py/fs.ts'), 'utf8'), {
  fileName: 'fs.ts', compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext },
});
if (fsTypes.diagnostics?.length) throw new Error(ts.formatDiagnosticsWithColorAndContext(fsTypes.diagnostics, {
  getCanonicalFileName: path => path, getCurrentDirectory: () => pkg, getNewLine: () => '\n',
}));
writeFileSync(join(pkg, 'dist/fs.d.ts'), fsTypes.outputText);
const result = await build({ entryPoints: [join(pkg, 'src/browser.ts')], outfile: join(pkg, 'dist/browser.js'),
  bundle: true, platform: 'browser', format: 'esm', target: 'es2022', conditions: ['browser'],
  minify: true, metafile: true, sourcemap: true, legalComments: 'linked' });
const builtins = Object.keys(result.metafile!.inputs).filter((path) => path.startsWith('node:'));
if (builtins.length) throw new Error(`Node modules in browser bundle: ${builtins.join(', ')}`);
const bytes = readFileSync(join(pkg, 'dist/browser.js'));
const report = { assets: Object.keys(files).length, assetBytes: Object.values(files).reduce((n, s) => n + Buffer.byteLength(s), 0),
  bytes: bytes.length, gzipBytes: gzipSync(bytes).length, nodeBuiltins: builtins,
  inputs: Object.keys(result.metafile!.inputs).map((path) => relative(root, resolve(path))) };
writeFileSync(join(pkg, 'dist/browser-build.json'), JSON.stringify(report, null, 2));
console.log(JSON.stringify({ ...report, inputs: report.inputs.length }));
