// ``hashlib.sha256(s.encode()).hexdigest()`` / ``hashlib.md5(...)`` in pure TS
// (MIGRATION_PLAN.md §4) — no ``node:crypto`` so the engine runs in browsers.
//
//   hashlib.sha256(text.encode("utf-8")).hexdigest() -> sha256Hex(text)
//   hashlib.md5(text.encode()).hexdigest()           -> md5Hex(text)

import { ValueError } from './errors.ts';

/** ``text.encode("utf-8")`` (strict: lone surrogates raise like Python). */
export function utf8Encode(text: string): Uint8Array {
  const bytes: number[] = [];
  for (const ch of text) {
    const code = ch.codePointAt(0)!;
    if (code < 0x80) {
      bytes.push(code);
    } else if (code < 0x800) {
      bytes.push(0xc0 | (code >> 6), 0x80 | (code & 0x3f));
    } else if (code < 0x10000) {
      if (code >= 0xd800 && code <= 0xdfff) {
        throw new ValueError("'utf-8' codec can't encode character: surrogates not allowed");
      }
      bytes.push(0xe0 | (code >> 12), 0x80 | ((code >> 6) & 0x3f), 0x80 | (code & 0x3f));
    } else {
      bytes.push(0xf0 | (code >> 18), 0x80 | ((code >> 12) & 0x3f), 0x80 | ((code >> 6) & 0x3f), 0x80 | (code & 0x3f));
    }
  }
  return Uint8Array.from(bytes);
}

function toBytes(input: string | Uint8Array): Uint8Array {
  return typeof input === 'string' ? utf8Encode(input) : input;
}

function hex(bytes: ArrayLike<number>): string {
  let out = '';
  for (let i = 0; i < bytes.length; i += 1) out += bytes[i].toString(16).padStart(2, '0');
  return out;
}

